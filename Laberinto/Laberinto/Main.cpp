#include <iostream>

using namespace std;

int main()
{
	cout << "---------------------------Laberinto A_B---------------------------" << endl;
	char laberinto[10][10] = {
		{'A','*',' ',' ',' ',' ',' ',' ',' ','*'},
		{' ','*',' ',' ',' ',' ','*','*',' ','*'},
		{' ','*',' ','*','*',' ','*','*','*','*'},
		{' ','*',' ','*',' ',' ','*',' ',' ',' '},
		{' ',' ',' ','*',' ',' ',' ',' ','*','*'},
		{' ','*','*','*','*','*',' ',' ','*',' '},
		{' ',' ',' ',' ','*',' ',' ',' ',' ',' '},
		{' ','*','*',' ','*',' ',' ','*','*','*'},
		{'*','*',' ',' ','*',' ',' ','*',' ',' '},
		{' ',' ',' ','*','*',' ',' ',' ',' ','B'}
	};

	//Graficamos el laberinto
	for (char(*filas)[10] = laberinto; filas < laberinto + 10; filas++)
	{
		for (char* columnas = *filas; columnas < *filas + 10; columnas++)
		{
			cout << *columnas << " ";
		}
		cout <<"|" << endl;
	}
	cout << "---------------------";
}